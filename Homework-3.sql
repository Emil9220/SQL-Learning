 -----TASK-9----

 SELECT L.CITY, ROUND(AVG(A.SALARY),0) AS ORTA_MAAS, COUNT(A.JOB_ID) AS ISCI_SAYI  
 FROM HR.EMPLOYEES A
 JOIN HR.DEPARTMENTS D ON A.DEPARTMENT_ID=D.DEPARTMENT_ID
 JOIN HR.LOCATIONS L ON L.LOCATION_ID = D.LOCATION_ID
 GROUP BY L.CITY 
 HAVING COUNT(A.JOB_ID)>5
 ORDER BY ISCI_SAYI DESC


