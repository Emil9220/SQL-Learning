SELECT 
    MANAGER_ID, 
    COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NOT NULL
GROUP BY MANAGER_ID
ORDER BY ISCI_SAYI DESC;



---TASK-2---

SELECT 
COUNTRY_ID,COUNT(*) AS OFIS_SAYI
FROM HR.LOCATIONS
WHERE COUNTRY_ID IS NOT NULL
GROUP BY COUNTRY_ID
ORDER BY OFIS_SAYI DESC

