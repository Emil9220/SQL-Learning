SELECT J.JOB_TITLE, E.LAST_NAME, AVG(E.SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J ON E.JOB_ID = JOB_ID
WHERE AVG(E.SALARY) > 10000
GROUP BY J.JOB_TITLE;

